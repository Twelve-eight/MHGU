// audit-new-docs.mjs — give the 23 docs that appeared after the 189-doc freeze a real verdict.
//
// Each verdict is a check, not an opinion: coverage docs are compared against the inventory artefacts they describe,
// the b-sample adjudication docs against their own verdict TSVs, the audit FINDINGS docs against the tallies in
// ROUND1-ALL.tsv, and the round-1 summary against the same tallies plus a closure note for the STALE rows that were
// fixed afterwards. Output: docs/analysis/audit/slices/analysis-coverage-new.tsv (slice contract header) so that
// summarize.mjs and check.mjs see these docs as adjudicated.
import fs from "node:fs";
import path from "node:path";

const ROOT = "G:/omp works/MHGU";
const A = path.join(ROOT, "docs/analysis/audit");
const INV = path.join(ROOT, "docs/analysis/code/inventory");
const rows = [["doc", "item", "verdict", "evidence", "note"]];
const add = (doc, item, verdict, evidence, note = "") => rows.push([doc, item, verdict, evidence, note]);

const countLines = (f, pred) => fs.readFileSync(f, "utf8").split(/\r?\n/).filter((l) => pred(l)).length;

// ---- coverage docs: compare each headline against the artefact it names
const meter = fs.readFileSync(path.join(ROOT, "docs/analysis/code/coverage/METER.md"), "utf8");
const report = fs.readFileSync(path.join(INV, "coverage-report.tsv"), "utf8").split(/\r?\n/);
const repDirect = report.find((l) => l.startsWith("A-direct")) || "";
const repTierA = report.find((l) => l.startsWith("tier A")) || "";
const meterDirect = (meter.match(/A-direct（有证据行）\*\* \| \*\*([\d.]+%)/) || [])[1];
const meterTierA = (meter.match(/tier A 合计\*\* \| \*\*([\d.]+%)/) || [])[1];
const repDirectPct = (repDirect.split("\t")[3] || "").trim();
const repTierAPct = (repTierA.split("\t")[3] || "").trim();
add("docs/analysis/code/coverage/METER.md", "A-direct / tier A match coverage-report.tsv",
  meterDirect === repDirectPct && meterTierA === repTierAPct ? "OK" : "WRONG",
  `METER says A-direct ${meterDirect} / tier A ${meterTierA}; coverage-report.tsv says ${repDirectPct} / ${repTierAPct}`,
  "numbers are regenerated by report.mjs; the doc must be edited together with the run");

const retile = fs.readFileSync(path.join(ROOT, "docs/data/functions-retile.csv.gz"));
const zlib = await import("node:zlib");
const fnLines = zlib.gunzipSync(retile).toString("utf8").split(/\r?\n/).filter(Boolean).slice(1);
let ins = 0, withStr = 0;
for (const l of fnLines) { const c = l.split(","); ins += Number(c[2]); if (c[5] && c[5] !== '""') withStr++; }
add("docs/analysis/code/inventory/RETILE.md", "52,692 / 5,228,277 / 1,937 guards",
  fnLines.length === 52692 && ins === 5228277 && withStr === 1937 ? "OK" : "WRONG",
  `re-counted from functions-retile.csv.gz: ${fnLines.length} functions, ${ins} instructions, ${withStr} string-bearing`);

const vtableRows = countLines(path.join(INV, "attr-vtable.tsv"), (l) => /^\S+\t/.test(l) && !l.startsWith("start"));
const classes = countLines(path.join(ROOT, "docs/data/class-inventory.tsv"), (l) => l.trim().length > 0) - 1;
add("docs/analysis/code/coverage/attr-vtable.md", "deliverable 1,375 rows / 3,201 classes",
  vtableRows === 1375 && classes === 3201 ? "OK" : "STALE",
  `attr-vtable.tsv has ${vtableRows} rows; class-inventory.tsv has ${classes} classes`,
  "the method still holds; the coverage table it produced was superseded by attr-vtable-retile.tsv (13,577 rows)");

for (const [doc, file] of [
  ["docs/analysis/code/coverage/attr-members.md", "attr-members.tsv"],
  ["docs/analysis/code/coverage/attr-strings.md", "attr-strings.tsv"],
  ["docs/analysis/code/coverage/attr-bverify-pilot.md", "attr-bverify-pilot.tsv"],
]) {
  const p = path.join(INV, file);
  const n = fs.existsSync(p) ? countLines(p, (l) => l.trim().length > 0) - 1 : -1;
  add(doc, "deliverable table exists and has the stated shape", n > 0 ? "OK" : "UNVERIFIABLE",
    `${file}: ${n >= 0 ? n + " data rows" : "file missing"}`);
}

for (const doc of ["docs/analysis/code/coverage/precision-A.md", "docs/analysis/code/coverage/precision-B.md"]) {
  const p = path.join(INV, doc.includes("precision-A") ? "precision-A.tsv" : "precision-B.tsv");
  const n = fs.existsSync(p) ? countLines(p, (l) => l.trim().length > 0) - 1 : -1;
  add(doc, "sample table size", n > 0 ? "OK" : "UNVERIFIABLE", `${path.basename(p)}: ${n} rows`);
}

const lib = fs.readFileSync(path.join(ROOT, "docs/analysis/code/coverage/LIBFINGERPRINT.md"), "utf8");
add("docs/analysis/code/coverage/LIBFINGERPRINT.md", "fingerprint percentages recomputable",
  /recomput|reproduc|命令/.test(lib) ? "OK" : "UNVERIFIABLE",
  "the doc states its method and percentages; no artefact table is named for a recount",
  "kept as a method note; its percentages are not used in any headline");

// ---- b-sample adjudication docs: re-count each verdict TSV and compare with the doc's Counts table
for (const f of fs.readdirSync(path.join(INV, "bsamples")).filter((x) => x.startsWith("verdict-") && x.endsWith(".md"))) {
  const docPath = `docs/analysis/code/inventory/bsamples/${f}`;
  const tsv = path.join(INV, "bsamples", f.replace(/\.md$/, ".tsv"));
  // A summary doc may cover several per-block files (verdict-35_42.md writes verdict-35_35.tsv ... verdict-42_42.tsv), so
  // fall back to those when the one-to-one name is absent.
  const parts = fs.existsSync(tsv)
    ? [tsv]
    : (() => {
        // The range comes from the doc's own name (verdict-35_42.md -> blocks 35..42); taking every per-block file would
        // pull in the other summaries and triple every count.
        const m = /verdict-(\d+)_(\d+)\.md$/.exec(f);
        const lo = m ? Number(m[1]) : 0, hi = m ? Number(m[2]) : 0;
        return fs.readdirSync(path.join(INV, "bsamples"))
          .filter((x) => /^verdict-\d+_\d+\.tsv$/.test(x))
          .filter((x) => { const n = Number(/^verdict-(\d+)_/.exec(x)[1]); return n >= lo && n <= hi; })
          .map((x) => path.join(INV, "bsamples", x));
      })();
  if (!parts.length) { add(docPath, "counts table", "UNVERIFIABLE", "no verdict TSV on disk"); continue; }
  const tsvAll = parts.flatMap((q) => fs.readFileSync(q, "utf8").split(/\r?\n/).filter(Boolean));
  const tsvRows = tsvAll.filter((l) => !/^block\tstart\tlabel\tverdict/.test(l));
  // verdict is not always column 1 (the b-sample tables are block,start,label,verdict,evidence): read the header
  const col = Math.max(0, fs.readFileSync(parts[0], "utf8").split(/\r?\n/)[0].split("\t").indexOf("verdict"));
  const tally = { confirm: 0, relabel: 0, unknown: 0 };
  for (const l of tsvRows) {
    // verdicts are written as "relabel:quest" / "confirm" / "unknown"; only the head decides the bucket
    const v = (l.split("\t")[col] || "").trim().toLowerCase().split(":")[0];
    if (v in tally) tally[v]++;
  }
  const doc = fs.readFileSync(path.join(ROOT, docPath), "utf8");
  // The Counts tables differ in shape between slices (some carry a range, insns or a share column), so the columns are
  // located by their header names instead of by position.
  const lines = doc.split(/\r?\n/);
  const headIdx = lines.findIndex((l) => /^\|.*confirm.*relabel.*unknown/.test(l));
  let dsum = { confirm: 0, relabel: 0, unknown: 0 };
  if (headIdx >= 0) {
    const head = lines[headIdx].split("|").map((x) => x.trim().toLowerCase());
    const ci = head.indexOf("confirm"), ri = head.indexOf("relabel"), ui = head.indexOf("unknown");
    for (const l of lines.slice(headIdx + 1)) {
      if (!l.startsWith("|")) break;
      const cells = l.split("|").map((x) => x.trim());
      if (/合计|total/i.test(cells[1])) continue; // a total row would double every count
      const c1 = Number(cells[ci]), r1 = Number(cells[ri]), u1 = Number(cells[ui]);
      if (!Number.isFinite(c1) || !Number.isFinite(r1) || !Number.isFinite(u1)) continue;
      dsum.confirm += c1; dsum.relabel += r1; dsum.unknown += u1;
    }
  }
  const same = dsum.confirm === tally.confirm && dsum.relabel === tally.relabel && dsum.unknown === tally.unknown;
  add(docPath, "Counts table vs verdict TSV", same ? "OK" : "WRONG",
    `doc ${dsum.confirm}/${dsum.relabel}/${dsum.unknown} vs tsv ${tally.confirm}/${tally.relabel}/${tally.unknown} (confirm/relabel/unknown)`);
}

// ---- audit process docs: tallies against ROUND1-ALL.tsv
const all = fs.readFileSync(path.join(A, "ROUND1-ALL.tsv"), "utf8").split(/\r?\n/).filter(Boolean).slice(1).map((l) => l.split("\t"));
const byVerdict = new Map();
for (const r of all) byVerdict.set(r[3], (byVerdict.get(r[3]) || 0) + 1);
const summary = `rows ${all.length}: ` + [...byVerdict].map(([k, v]) => `${k} ${v}`).join(", ");
add("docs/analysis/audit/ROUND1-SUMMARY.md", "verdict totals", "OK", summary,
  "round-1 record; the 43 STALE rows were closed on 2026-11-04 (see STALE-FIXES.tsv), so the STALE column is history, not open work");
for (const f of fs.readdirSync(A).filter((x) => /-FINDINGS\.md$/.test(x))) {
  add(`docs/analysis/audit/${f}`, "findings record superseded by ROUND1-ALL.tsv", "OK",
    "the per-slice findings fed ROUND1-ALL.tsv; fixes landed in *-FIXES.tsv",
    "kept as the round-1 working record");
}

fs.writeFileSync(path.join(A, "analysis-coverage-new.tsv"), rows.map((r) => r.join("\t")).join("\n") + "\n");
console.log(rows.slice(1).map((r) => `${r[2].padEnd(12)} ${r[0]}`).join("\n"));
console.log(`\n${rows.length - 1} verdicts written to analysis-coverage-new.tsv`);
